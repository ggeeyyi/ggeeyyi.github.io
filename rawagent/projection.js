/* The projection view replays frozen images and measurements from the project. */
(() => {
  "use strict";
  const asset = window.rawAgentAsset || (file => file);

  const rounds = [
    { number: "01", score: "28.32", change: "高斯插值与双边滤波" },
    { number: "06", score: "29.90", change: "引导插值与图块去噪" },
    { number: "09", score: "31.17", change: "加入引导滤波，入选隐藏评测" }
  ];
  const stages = [
    { label: "研究问题", title: "从一张 RAW，恢复一幅彩色图像", render: opening },
    { label: "传感器", title: "一个像素只记录一个数", render: sampling },
    { label: "代码生成", title: "评分反馈怎样改变代码？", render: generation },
    { label: "自适应算法", title: "藏起部分读数，让算法作选择", render: adaptation },
    { label: "泛化实验", title: "换传感器，再换照片", render: transfer },
    { label: "真机验证", title: "回到真正的相机 RAW", render: cameras },
    // Generated by build_models.py; absent when the multi-model summary has not been built.
    ...(window.RAWAGENT_MODELS_STAGE ? [{ label: window.RAWAGENT_MODELS_STAGE.label, title: window.RAWAGENT_MODELS_STAGE.title, render: () => window.RAWAGENT_MODELS_STAGE.html }] : [])
  ];

  function opening() {
    const sample = window.RAWAGENT_CASES?.find(item => item.id === "astronaut");
    const fragment = document.createElement("div");
    fragment.className = "rap-opening";
    const pair = document.createElement("div");
    pair.className = "rap-pair";
    if (sample) {
      for (const [src, label] of [[sample.raw, "模拟传感器 RAW"], [sample.output, "v1.1.0 重建"]]) {
        const figure = document.createElement("figure");
        const image = new Image();
        image.src = src;
        image.alt = sample.title + " · " + label;
        const caption = document.createElement("figcaption");
        caption.textContent = label;
        figure.append(image, caption);
        pair.append(figure);
      }
    }
    const footer = document.createElement("div");
    footer.className = "rap-opening-caption";
    const note = document.createElement("p");
    note.textContent = "项目先用编码模型探索图像处理方案。这里展示后续冻结的 v1.1.0，它依据滤色阵列和噪声标定恢复 RGB。";
    const stats = document.createElement("small");
    stats.textContent = sample ? sample.layout + " · " + sample.level + " · PSNR " + sample.psnr.toFixed(2) + " dB · NASA 公有领域照片模拟" : "编码模型生成 ISP，CPU 执行重建。";
    footer.append(note, stats);
    fragment.append(pair, footer);
    return fragment;
  }

  function sampling() {
    return `<div class="rap-grid rap-sampling">
      <figure class="rap-tile-figure"><div class="rap-tile" role="img" aria-label="RGBW 周期单元，上行为红、绿，下行为白、蓝">
        <span class="rap-filter-r">R</span><span class="rap-filter-g">G</span>
        <span class="rap-filter-w">W</span><span class="rap-filter-b">B</span>
      </div><figcaption>RGBW 滤色阵列的一个重复单元</figcaption></figure>
      <div class="rap-text"><h3>白色滤片同时响应三种颜色</h3>
        <p>RGBW 模型中，W 位置测到的是三个线性通道的加权和。</p>
        <div class="rap-formula" aria-label="W 等于 0.72 R 加 0.86 G 加 0.62 B">W = 0.72R + 0.86G + 0.62B</div>
        <p>重建程序结合相邻位置、滤片响应、曝光和噪声估计，推断每个像素的完整 RGB。</p>
      </div></div>`;
  }

  function generation() {
    return `<div class="rap-rounds">${rounds.map(round => `<figure>
      <img src="${asset("evidence-assets/round-" + round.number + ".png")}" alt="第 ${Number(round.number)} 轮候选程序的归档重建预览">
      <figcaption><span>第 ${Number(round.number)} 轮</span><b>${round.score} <small>dB</small></b><p>${round.change}</p></figcaption>
    </figure>`).join("")}</div>
    <p class="rap-note"><strong>RGGB · 成像知识 · 第三次运行</strong>　画面为同一场景，分数是开发集均值。四种阵列各做三次运行，原实验里给评分反馈加上成像知识，低照隐藏集平均提高 0.46 dB；换三个模型重复后没有复现，见最后一页。</p>`;
  }

  function adaptation() {
    return `<div class="rap-grid rap-decision">
      <div class="rap-text"><div class="rap-giant">112 <small>个</small></div>
        <h3>暂时遮住的 RAW 位置</h3><p>v1.1.0 在这张低照咖啡图的两个小窗口遮住读数，再检验三种候选预测。</p></div>
      <div class="rap-risk"><div class="rap-risk-caption">候选方法<span>遮挡预测误差 ↓</span></div>
        <div>保留物理重建<b>5.054</b></div><div>局部拟合<b>5.049</b></div><div class="rap-picked">图块去噪 <small>本图选用</small><b>4.536</b></div>
      </div></div><p class="rap-note">在整图上执行 85 步物理重建后应用选定的校正。本例的遮挡预测改善，最终 RGB 比固定物理重建低 0.16 dB。</p>`;
  }

  function transfer() {
    return `<div class="rap-grid rap-transfer"><div class="rap-text"><h3>跨传感器的输入覆盖</h3>
      <div class="rap-coverage"><b>1,728</b> / 1,728</div><p>v1.1.0 完成全部外部输入。v1.0.0 支持其中 864 张。</p></div>
      <div class="rap-study"><h3>未见过的自然照片</h3>
        <div><span>固定物理重建</span><b>29.97 <small>dB</small></b></div>
        <div><span>自适应选择</span><b>29.53 <small>dB</small></b></div>
        <p>BSDS500 的 20 个摄影源共 480 张模拟 RAW。固定方法在每个来源的平均分都领先。</p>
      </div></div><p class="rap-note"><strong>实际选择</strong>　面对未知自然照片，优先尝试固定物理重建。</p>`;
  }

  function cameras() {
    return `<div class="rap-pair rap-cameras">
      <figure><img src="${asset('evidence-assets/ricoh.png')}" alt="理光相机原始马赛克的重建裁块"><figcaption><b>Ricoh GR III</b><span>2 × 2 Bayer · 留出误差 1.355%</span></figcaption></figure>
      <figure><img src="${asset('evidence-assets/fuji.png')}" alt="富士相机原始马赛克的重建裁块"><figcaption><b>Fujifilm X-T4</b><span>6 × 6 X-Trans · 留出误差 0.434%</span></figcaption></figure>
      </div><p class="rap-note">每台相机各取一张 RAW 的中心裁块，遮住 2% 的测量点，报告相对于可用数字范围的预测 RMSE。真机色彩准确度仍需配对的干净 RGB 参考验证。</p>`;
  }

  let dialog;
  let index = 0;
  let trigger;
  let oldOverflow;
  let ownsFullscreen = false;

  function initialize() {
    dialog = document.createElement("dialog");
    dialog.className = "rap-dialog";
    dialog.setAttribute("aria-label", "RawAgent 答辩放映");
    dialog.innerHTML = `<div class="rap-frame"><header class="rap-top">
      <div class="rap-brand"><span class="rap-brand-mark" aria-hidden="true"></span>RawAgent <span class="rap-mode">答辩放映</span></div>
      <div class="rap-controls"><button type="button" class="rap-screen">全屏</button><button type="button" class="rap-close">退出放映</button></div>
      </header><section class="rap-stage" aria-labelledby="rap-title"><div class="rap-heading"><span class="rap-label"></span><h2 id="rap-title" tabindex="-1"></h2></div>
      <div class="rap-body"></div></section><footer class="rap-footer"><div class="rap-progress"><span class="rap-count"></span><div class="rap-segments" aria-hidden="true"></div></div>
      <div class="rap-controls"><button type="button" class="rap-prev">上一页</button><button type="button" class="rap-next">下一页</button></div></footer>
      <p class="rap-announcer" aria-live="polite" aria-atomic="true"></p></div>`;
    document.body.append(dialog);
    const segments = dialog.querySelector(".rap-segments");
    for (const stage of stages) segments.append(document.createElement("span"));
    dialog.querySelector(".rap-prev").addEventListener("click", () => change(index - 1));
    dialog.querySelector(".rap-next").addEventListener("click", () => index === stages.length - 1 ? close() : change(index + 1));
    dialog.querySelector(".rap-close").addEventListener("click", close);
    const screen = dialog.querySelector(".rap-screen");
    screen.hidden = !document.fullscreenEnabled || !document.documentElement.requestFullscreen;
    screen.addEventListener("click", async () => {
      try {
        if (document.fullscreenElement) {
          await document.exitFullscreen();
        } else {
          await document.documentElement.requestFullscreen({ navigationUI: "hide" });
          ownsFullscreen = true;
        }
      } catch {
        screen.hidden = true;
      }
    });
    document.addEventListener("fullscreenchange", () => {
      screen.textContent = document.fullscreenElement ? "退出全屏" : "全屏";
      if (!document.fullscreenElement) ownsFullscreen = false;
    });
    dialog.addEventListener("close", () => {
      document.documentElement.style.overflow = oldOverflow;
      if (ownsFullscreen && document.fullscreenElement) document.exitFullscreen().catch(() => {});
      ownsFullscreen = false;
      if (trigger?.isConnected) trigger.focus({ preventScroll: true });
    });
    dialog.addEventListener("keydown", event => {
      if (event.altKey || event.ctrlKey || event.metaKey) return;
      let target;
      if (event.key === "ArrowRight" || event.key === "PageDown") target = index + 1;
      if (event.key === "ArrowLeft" || event.key === "PageUp") target = index - 1;
      if (event.key === "Home") target = 0;
      if (event.key === "End") target = stages.length - 1;
      if (event.key === " " && !event.target.closest("button")) target = index + (event.shiftKey ? -1 : 1);
      if (target === undefined) return;
      event.preventDefault();
      change(target);
    });
  }

  function change(nextIndex) {
    index = Math.max(0, Math.min(stages.length - 1, nextIndex));
    const stage = stages[index];
    dialog.querySelector(".rap-label").textContent = stage.label;
    dialog.querySelector("#rap-title").textContent = stage.title;
    const content = stage.render();
    const body = dialog.querySelector(".rap-body");
    if (typeof content === "string") body.innerHTML = content;
    else body.replaceChildren(content);
    dialog.querySelector(".rap-prev").disabled = index === 0;
    dialog.querySelector(".rap-next").textContent = index === stages.length - 1 ? "结束放映" : "下一页";
    dialog.querySelector(".rap-count").textContent = (index + 1) + " / " + stages.length;
    dialog.querySelectorAll(".rap-segments span").forEach((segment, at) => segment.classList.toggle("rap-filled", at <= index));
    dialog.querySelector(".rap-announcer").textContent = "第 " + (index + 1) + " 页，共 " + stages.length + " 页。" + stage.title;
    dialog.querySelector(".rap-stage").scrollTop = 0;
  }

  function open() {
    if (!dialog) initialize();
    if (dialog.open) return;
    trigger = document.activeElement;
    oldOverflow = document.documentElement.style.overflow;
    document.documentElement.style.overflow = "hidden";
    change(0);
    dialog.showModal();
    dialog.querySelector("#rap-title").focus({ preventScroll: true });
  }

  function close() {
    if (dialog?.open) dialog.close();
  }

  window.RawAgentProjection = Object.freeze({ open, close });
})();
